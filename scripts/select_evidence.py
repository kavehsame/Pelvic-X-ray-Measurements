"""Publish one complete passing software-check run per edition, without private logs."""

import argparse
import csv
from html import escape
import json
from pathlib import Path
import shutil
import xml.etree.ElementTree as ET

from project import EXTENSION, WEB, source_hashes, within


def load(path):
    return json.loads(path.read_text())


def cases(path):
    tree = ET.parse(path)
    root = tree.getroot()
    if any(root.findall(".//" + name) for name in ("failure", "error", "skipped")):
        raise ValueError("Only a fully passing unit suite can be selected.")
    rows = root.findall(".//testcase")
    assert rows
    for element in root.iter():
        for name in ("hostname", "file"):
            element.attrib.pop(name, None)
    return rows, tree


def table(rows):
    return (
        "<table><tr><th>Test</th><th>Result</th></tr>"
        + "".join(
            "<tr><td>"
            + escape(row.get("classname", "") + "." + row.get("name", ""))
            + "</td><td>Passed</td></tr>"
            for row in rows
        )
        + "</table>"
    )


def html(title, body):
    return (
        '<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>'
        + escape(title)
        + "</title><style>body{font:17px/1.6 system-ui;max-width:1050px;padding:24px;margin:auto;color:#17333c}a{color:#146b60}table{border-collapse:collapse;width:100%;font-size:14px}td,th{padding:9px;border-bottom:1px solid #ddd;text-align:left;overflow-wrap:anywhere}details{padding:14px;border:1px solid #ddd;border-radius:7px;margin:18px 0}summary{cursor:pointer;font-weight:600}h1{line-height:1.2}</style><h1>"
        + escape(title)
        + "</h1>"
        + body
        + "<p><strong>Research use only. This software is not a medical device.</strong> It is not intended for diagnosis, treatment planning or other clinical decision-making.</p></html>"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--run", type=Path, required=True)
    args = parser.parse_args()
    run = within(args.run)
    summary = load(run / "verification.json")
    if (
        summary["status"] != "passed"
        or not summary["live_slicer"]
        or not summary["source_unchanged"]
    ):
        raise ValueError("Select a passing full run with both live runtimes.")
    if load(run / "source_hashes.json") != source_hashes():
        raise ValueError("Current source differs from the selected run.")
    native = load(run / "slicer/verification.json")
    chrome = load(run / "web/chrome_checks.json")
    core = load(run / "web/core_checks.json")
    downloads = load(run / "web/download_checks.json")
    presentation = load(run / "web/presentation_checks.json")
    assert all(item["status"] == "passed" for item in (native, chrome, core, downloads, presentation))
    test_sets = {
        "slicer": cases(run / "slicer/unit.junit.xml"),
        "web": cases(run / "web_unit.xml"),
    }
    limitation = "<p>A validation study is being performed to compare the tool with established medical software. These synthetic software checks are separate from that study; they do not establish clinical validity. The fixed reference was generated by an earlier implementation and is not an independent clinical comparator.</p>"
    config = (
        "<p>Run: "
        + escape(summary["started_utc"])
        + ". Platform: "
        + escape(summary["platform"] + " " + summary["machine"])
        + ". Python: "
        + escape(summary["python"])
        + ".</p>"
    )
    for edition, base in (("slicer", EXTENSION), ("web", WEB)):
        target = within(base / "test_reports/current")
        if target.exists():
            raise ValueError(
                "The selected evidence folder already exists. Preserve it in version history before replacing it."
            )
        target.mkdir(parents=True)
        rows, tree = test_sets[edition]
        tree.write(target / "unit.junit.xml", encoding="utf-8", xml_declaration=True)
        selected = {
            **summary,
            "edition": edition,
            "unit_tests": len(rows),
            "runtime": native["runtime"]
            if edition == "slicer"
            else {"browser": chrome["chrome"]},
        }
        (target / "summary.json").write_text(json.dumps(selected, indent=2) + "\n")
        interchange = run / "web/planning_interchange/result.json"
        assert load(interchange)["status"] == "passed"
        shutil.copyfile(interchange, target / "planning_interchange.json")
        body = config + f"<p>All {len(rows)} unit tests passed.</p>"
        body += '<p>The <a href="planning_interchange.json">Planning CSV round trip</a> checks template coordinates, wear and fragment pixels from web to Slicer and back.</p>'
        if edition == "slicer":
            body += (
                "<p>Slicer "
                + escape(native["runtime"]["version"])
                + ", revision "
                + escape(native["runtime"]["revision"])
                + ".</p>"
            )
            replay = target / "replay"
            replay.mkdir()
            for name in (
                "comparison_report.html",
                "comparison_report.md",
                "comparison_details.csv",
                "comparison_summary.json",
            ):
                shutil.copyfile(run / "slicer/replay/comparison" / name, replay / name)
            expected = (
                EXTENSION
                / "Testing/Python/end_to_end_replay/dummy_expected_full_export.csv"
            )
            actual = (
                run
                / "slicer/replay/actual_export/SyntheticFullCase/SyntheticFullCase.dcm_measurements.csv"
            )
            comparison = load(run / "slicer/replay/comparison/comparison_summary.json")
            assert comparison["passed"]
            with expected.open(newline="") as stream:
                count = len(list(csv.DictReader(stream)))
            shutil.copyfile(expected, replay / "expected.csv")
            shutil.copyfile(actual, replay / "actual.csv")
            shutil.copyfile(
                run / "slicer/replay/verification.json", target / "replay.json"
            )
            agreement = "byte for byte" if comparison["raw_byte_match"] else f"with {comparison['roundoff_field_count']} numeric fields within the {comparison['max_numeric_ulps']}-step floating-point rounding limit"
            body += f'<p>The full CSV replay matched all {count} reference rows {agreement}. Smart Point Placement and live multi-guide, morphology, leg-length, circle-visibility and four-contour workflow checks also passed.</p><p><a href="replay/comparison_report.html">Interactive CSV and coordinate comparison</a></p>'
        else:
            for name in ("chrome_checks.json", "core_checks.json", "download_checks.json", "presentation_checks.json"):
                shutil.copyfile(run / "web" / name, target / name)
            comparison = chrome["chrome_replay"]
            body += f"<p>{len(chrome['tests'])} Chrome workflow groups passed. The full browser export reproduced {comparison['measurements']} measurements and {comparison['numeric_values']} numeric values; maximum absolute difference {comparison['max_absolute_difference']:.3g}.</p><p>The test host disconnected before synthetic images were selected. The cached software started offline and the browser completed loading, annotation and local export.</p>"
            body += (
                "<details><summary>Chrome workflow groups</summary><ol>"
                + "".join("<li>" + escape(t) + "</li>" for t in chrome["tests"])
                + '</ol></details><p><a href="chrome_checks.json">Browser evidence</a> · <a href="core_checks.json">Core replay evidence</a></p>'
            )
            body += f'<p>{len(downloads["tests"])} component-delivery scenarios passed, including blocked binary routes, HTTP failures, altered responses, interrupted-download recovery and unavailable storage. <a href="download_checks.json">Download checks</a>. These simulated conditions do not establish access through a particular hospital network.</p>'
            body += f'<p>{len(presentation["tests"])} presentation checks passed for export resolution, summary placement, both wall contours, curved previews, larger help, landmark picking, magnified panning and direct case navigation. <a href="presentation_checks.json">Presentation evidence</a>.</p>'
        body += (
            limitation
            + "<details><summary>Unit-test cases</summary>"
            + table(rows)
            + '</details><p><a href="unit.junit.xml">JUnit results</a> · <a href="summary.json">Run summary</a></p>'
        )
        (target / "index.html").write_text(
            html(edition.title() + " software checks", body)
        )
    print("One passing run selected for each edition.")


if __name__ == "__main__":
    main()
