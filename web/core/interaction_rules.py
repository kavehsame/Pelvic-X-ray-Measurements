"""Fork-owned copies of desktop landmark reuse and local edge attraction.

Generated by scripts/port_interaction_helpers.py; browser adapters live in landmarks.py.
"""

from typing import Any
import numpy as np
from . import scene as vtk
from .geometry import lateral_reference_direction, superior_reference_direction, unit_vector, image_axes_from_volume

EPSILON = 1e-6
DEFAULT_CONSTRUCTION_LINE_LENGTH_SU = 40.0
ANATOMY_EDGE_CONTOUR_SNAP_RADIUS_PX = 6
ANATOMY_EDGE_CONTOUR_SNAP_SIGMA_PX = 3.0
ANATOMY_EDGE_CONTOUR_MIN_EDGE_ZSCORE = 1.0
SIDE_KEYS = ("left", "right")
ANATOMY_EDGE_CONTOUR_ROLES = (
    "iliopectinealLine",
    "ilioischialLine",
    "shentonLine",
    "acetabularRoofSourcil",
    "lineaTerminalis",
    "femoralShaftContour1",
    "femoralShaftContour2",
    "femoralShaftContour3",
    "femoralShaftContour4",
)
as_array = np.asarray
vector_length = np.linalg.norm


def plane_normal_from_volume(volume):
    return unit_vector(np.cross(*image_axes_from_volume(volume)))


class DesktopInteractionRules:
    def _role_points(self, role: Any) -> list[Any]:
        """Return defined world points for one role without creating new scene nodes."""
        node = self.get_node(role, create_if_missing=False)
        if node is None:
            return []
        return self._defined_points(node)

    def _side_role_points(self, base_role: str, side_key: Any) -> list[Any]:
        """Return defined world points for one side-specific role."""
        return self._role_points(self.side_role(base_role, side_key))

    def _pending_auto_line_endpoint_map(self) -> dict[Any, Any]:
        """Return the widget-local map of line roles waiting for an automatic second endpoint."""
        if not hasattr(self, "pending_auto_line_endpoints"):
            self.pending_auto_line_endpoints = {}
        return self.pending_auto_line_endpoints

    def _line_midpoint(self, base_role: str, side_key: Any) -> Any:
        """Return the midpoint of a side-specific line, if that line is defined."""
        points = self._side_role_points(base_role, side_key)
        if len(points) < 2:
            return None
        return 0.5 * (points[0] + points[1])

    def _first_side_point(self, base_role: str, side_key: Any) -> Any:
        """Return the first defined control point for one side-specific role."""
        points = self._side_role_points(base_role, side_key)
        if not points:
            return None
        return points[0]

    def _reference_direction(self) -> Any:
        """Return the current pelvic reference-line direction when available."""
        reference = self.latest_results.get("referenceLine", {})
        if not reference.get("defined"):
            return None
        return reference.get("direction")

    def _reference_superior_direction(self) -> Any:
        """Return the reference-perpendicular image-superior direction used by line-based tools."""
        reference_direction = self._reference_direction()
        if reference_direction is None:
            return None
        image_node = self.current_image_node()
        plane_normal = plane_normal_from_volume(image_node) if image_node is not None else None
        return superior_reference_direction(reference_direction, plane_normal, image_node)

    def _reference_lateral_direction(self, side_key: Any) -> Any:
        """Return the side-aware lateral direction along the pelvic reference line."""
        reference_direction = self._reference_direction()
        if reference_direction is None:
            return None
        return lateral_reference_direction(reference_direction, side_key, self.current_image_node())

    def _seed_line_half_length(self, anchor_point: Any = None) -> float:
        """Choose a readable seeded-line half length, matching the existing derived-axis scale."""
        fallback_points = [as_array(anchor_point)] if anchor_point is not None else []
        span = self._seed_display_span(self.current_image_node(), fallback_points)
        return max(float(DEFAULT_CONSTRUCTION_LINE_LENGTH_SU), float(span) * 0.12)

    def _line_points_through(self, anchor_point: Any, direction: Any) -> list[Any]:
        """Return two endpoints for an editable helper line centered on an anatomical landmark."""
        direction = unit_vector(direction)
        if direction is None:
            return []
        anchor = as_array(anchor_point)
        half_length = self._seed_line_half_length(anchor)
        return [anchor - direction * half_length, anchor + direction * half_length]

    def _seed_role_if_empty(self, role: Any, points: Any) -> bool:
        """Pre-fill one empty markup role without overwriting existing user input."""
        if not points:
            return False
        node = self.get_node(role, create_if_missing=True)
        if node is None or not node.IsA("vtkMRMLMarkupsNode"):
            return False
        if node.GetNumberOfDefinedControlPoints() > 0:
            return False
        labels = self._node_spec_for_role(role).get("labels", [])
        self._set_named_points(node, [as_array(point) for point in points], labels)
        self._make_seeded_markup_editable(node)
        return True

    def _make_seeded_markup_editable(self, node: Any) -> None:
        """Make a programmatically seeded user markup immediately draggable in slice views."""
        if node is None:
            return
        if hasattr(node, "SetSelectable"):
            node.SetSelectable(True)
        if hasattr(node, "SetLocked"):
            node.SetLocked(False)
        if hasattr(node, "SetNthControlPointLocked") and hasattr(node, "GetNumberOfControlPoints"):
            for point_index in range(node.GetNumberOfControlPoints()):
                node.SetNthControlPointLocked(point_index, False)
        node.SetDisplayVisibility(True)
        display_node = node.GetDisplayNode() if hasattr(node, "GetDisplayNode") else None
        if display_node is not None:
            if hasattr(display_node, "SetSelectable"):
                display_node.SetSelectable(True)
            if hasattr(display_node, "SetVisibility"):
                display_node.SetVisibility(True)
            if hasattr(display_node, "SetHandlesInteractive"):
                display_node.SetHandlesInteractive(False)
            if hasattr(display_node, "SetTranslationHandleVisibility"):
                display_node.SetTranslationHandleVisibility(False)
            if hasattr(display_node, "SetRotationHandleVisibility"):
                display_node.SetRotationHandleVisibility(False)
            if hasattr(display_node, "SetScaleHandleVisibility"):
                display_node.SetScaleHandleVisibility(False)
            if hasattr(display_node, "SetInteractionHandleScale"):
                display_node.SetInteractionHandleScale(0.0)
            if hasattr(display_node, "SetVisibility2D"):
                display_node.SetVisibility2D(True)

    def _queue_acetabular_angle_lateral_endpoint(self, base_role: str, side_key: Any) -> bool:
        """Use a known lateral sourcil as the second endpoint after the user places the base point."""
        lateral_sourcil = self._lateral_sourcil_point(side_key)
        if lateral_sourcil is None:
            return False
        role = self.side_role(base_role, side_key)
        self._pending_auto_line_endpoint_map()[role] = as_array(lateral_sourcil)
        return True

    def _complete_pending_auto_line_endpoint(self, role: Any) -> bool:
        """Complete a one-point line using a queued anatomical endpoint."""
        if role is None:
            return False
        pending_endpoints = self._pending_auto_line_endpoint_map()
        lateral_endpoint = pending_endpoints.get(role)
        if lateral_endpoint is None:
            return False
        node = self.get_node(role, create_if_missing=False)
        if node is None or not node.IsA("vtkMRMLMarkupsNode"):
            pending_endpoints.pop(role, None)
            return False
        points = self._defined_points(node)
        if len(points) >= 2:
            pending_endpoints.pop(role, None)
            return False
        if len(points) != 1:
            return False
        base_point = points[0]
        if vector_length(as_array(lateral_endpoint) - as_array(base_point)) <= EPSILON:
            return False
        pending_endpoints.pop(role, None)
        labels = self._node_spec_for_role(role).get("labels", [])
        self._set_named_points(node, [base_point, lateral_endpoint], labels)
        self._make_seeded_markup_editable(node)
        return True

    def _seed_side_role_if_empty(self, base_role: str, side_key: Any, points: Any) -> bool:
        """Pre-fill one side-specific markup role without overwriting existing user input."""
        return self._seed_role_if_empty(self.side_role(base_role, side_key), points)

    def _sharp_teardrop_point(self, side_key: Any) -> Any:
        """Infer the Sharp-angle teardrop point for the active side.

        Sharp stores the teardrop explicitly as its first endpoint. The acetabular-offset medial
        line passes through the teardrop, so its midpoint is the best available editable fallback
        when the offset line was generated from a teardrop seed.
        """
        point = self._first_side_point("sharpAngleLine", side_key)
        if point is not None:
            return point
        return self._line_midpoint("acetabularOffsetLineA", side_key)

    def _tonnis_medial_sourcil_point(self, side_key: Any) -> Any:
        """Infer the Tonnis medial-sourcil/base point for the active side."""
        return self._first_side_point("tonnisAngleLine", side_key)

    def _acetabular_angle_base_point(self, base_role: str, side_key: Any) -> Any:
        """Return the correct base landmark for one acetabular angle line role."""
        if base_role == "sharpAngleLine":
            return self._sharp_teardrop_point(side_key)
        if base_role == "tonnisAngleLine":
            return self._tonnis_medial_sourcil_point(side_key)
        return None

    def _lateral_sourcil_from_contour(self, side_key: Any) -> Any:
        """Infer the lateral sourcil from the lateral-most point of the sourcil contour."""
        points = self._side_role_points("acetabularRoofSourcil", side_key)
        if not points:
            return None
        lateral_direction = self._reference_lateral_direction(side_key)
        if lateral_direction is None:
            return None
        reference_points = self.latest_results.get("referenceLine", {}).get("points", [])
        origin = reference_points[0] if reference_points else np.zeros(3, dtype=float)
        return max(points, key=lambda point: float(np.dot(as_array(point) - origin, lateral_direction)))

    def _lateral_sourcil_point(self, side_key: Any) -> Any:
        """Infer the lateral sourcil/acetabular edge point from existing measurements."""
        explicit_candidates = [self._first_side_point("lceAnglePoint", side_key)]
        for base_role in ["tonnisAngleLine", "sharpAngleLine"]:
            points = self._side_role_points(base_role, side_key)
            if len(points) >= 2:
                explicit_candidates.append(points[1])
        explicit_candidates.append(self._lateral_sourcil_from_contour(side_key))
        for candidate in explicit_candidates:
            if candidate is not None:
                return candidate
        return self._line_midpoint("extrusionIndexMiddleLine", side_key)

    def _femur_head_radius(self, side_key: Any) -> Any:
        """Return the fitted native femoral-head radius in scene units, if available."""
        side_results = self.latest_results.get("sides", {}).get(side_key, {})
        femur_head = side_results.get("femurHead", {})
        diameter = femur_head.get("rawValue")
        if not femur_head.get("defined") or diameter is None or float(diameter) <= EPSILON:
            return None
        return 0.5 * float(diameter)

    def _femur_center_point(self, side_key: Any) -> Any:
        """Infer the native femoral-head center from fitted-center and derived LCE constructions."""
        side_results = self.latest_results.get("sides", {}).get(side_key, {})
        femur_head = side_results.get("femurHead", {})
        if femur_head.get("defined") and femur_head.get("center") is not None:
            return femur_head["center"]
        for base_role in ["femurHeadCenter", "lceAngleRadialArm", "lceAngleVisual"]:
            point = self._first_side_point(base_role, side_key)
            if point is not None:
                return point
        return None

    def _seed_acetabular_angle_line(self, base_role: str, side_key: Any) -> bool:
        """Seed a Sharp/Tonnis-style measured arm from teardrop and lateral sourcil landmarks."""
        teardrop = self._acetabular_angle_base_point(base_role, side_key)
        lateral_sourcil = self._lateral_sourcil_point(side_key)
        if teardrop is None or lateral_sourcil is None:
            return False
        if vector_length(as_array(lateral_sourcil) - as_array(teardrop)) <= EPSILON:
            return False
        return self._seed_side_role_if_empty(base_role, side_key, [teardrop, lateral_sourcil])

    def _seed_lce_point(self, side_key: Any) -> bool:
        """Seed the LCE point from an already known lateral sourcil landmark."""
        lateral_sourcil = self._lateral_sourcil_point(side_key)
        if lateral_sourcil is None:
            return False
        return self._seed_side_role_if_empty("lceAnglePoint", side_key, [lateral_sourcil])

    def _seed_acetabular_offset_lines(self, side_key: Any) -> bool:
        """Seed acetabular-offset lines from teardrop and femoral-head center landmarks."""
        direction = self._reference_superior_direction()
        if direction is None:
            return False
        seeded = False
        teardrop = self._sharp_teardrop_point(side_key)
        if teardrop is not None:
            seeded = (
                self._seed_side_role_if_empty(
                    "acetabularOffsetLineA", side_key, self._line_points_through(teardrop, direction)
                )
                or seeded
            )
        femur_center = self._femur_center_point(side_key)
        if femur_center is not None:
            seeded = (
                self._seed_side_role_if_empty(
                    "acetabularOffsetLineB", side_key, self._line_points_through(femur_center, direction)
                )
                or seeded
            )
        return seeded

    def _seed_femoral_offset_line(self, side_key: Any) -> bool:
        """Seed the femoral-offset line through the fitted femoral-head center."""
        side_results = self.latest_results.get("sides", {}).get(side_key, {})
        shaft_axis = side_results.get("femoralShaftAxis", {})
        direction = shaft_axis.get("direction")
        femur_center = self._femur_center_point(side_key)
        if not shaft_axis.get("defined") or direction is None or femur_center is None:
            return False
        return self._seed_side_role_if_empty(
            "femoralOffsetLine", side_key, self._line_points_through(femur_center, direction)
        )

    def _seed_extrusion_index_lines(self, side_key: Any) -> bool:
        """Seed FEI lines from the femoral-head circle and lateral sourcil when available."""
        offset_direction = self._reference_superior_direction()
        lateral_direction = self._reference_lateral_direction(side_key)
        if offset_direction is None:
            return False
        seeded = False
        femur_center = self._femur_center_point(side_key)
        femur_radius = self._femur_head_radius(side_key)
        if femur_center is not None and femur_radius is not None and (lateral_direction is not None):
            center = as_array(femur_center)
            medial_anchor = center - lateral_direction * femur_radius
            lateral_anchor = center + lateral_direction * femur_radius
            seeded = (
                self._seed_side_role_if_empty(
                    "extrusionIndexMedialLine", side_key, self._line_points_through(medial_anchor, offset_direction)
                )
                or seeded
            )
            seeded = (
                self._seed_side_role_if_empty(
                    "extrusionIndexLateralLine", side_key, self._line_points_through(lateral_anchor, offset_direction)
                )
                or seeded
            )
        lateral_sourcil = self._lateral_sourcil_point(side_key)
        if lateral_sourcil is not None:
            seeded = (
                self._seed_side_role_if_empty(
                    "extrusionIndexMiddleLine", side_key, self._line_points_through(lateral_sourcil, offset_direction)
                )
                or seeded
            )
        return seeded

    def is_snapping_anatomy_curve_points(self) -> bool:
        """Return whether a contour snap operation is already moving markup points."""
        return bool(getattr(self, "_snapping_anatomy_curve_points", False))

    def snap_anatomy_curve_to_edges(self, role: Any, image_node: Any) -> bool:
        """Move named anatomy-contour control points toward nearby high-contrast image edges.

        Slicer markups do not expose a built-in edge-attracting curve placement mode. This method
        adds a local posterior-style snap: gradient magnitude is the edge likelihood and a Gaussian
        centered at the user's click is the spatial prior.
        """
        if not self._is_anatomy_edge_contour_role(role) or image_node is None:
            return False
        node = self.get_node(role, create_if_missing=False)
        if node is None or not node.IsA("vtkMRMLMarkupsCurveNode"):
            return False
        image_array = self._edge_snap_image_array(image_node)
        if image_array is None:
            return False
        ras_to_ijk_matrix = vtk.vtkMatrix4x4()
        image_node.GetRASToIJKMatrix(ras_to_ijk_matrix)
        ijk_to_ras_matrix = vtk.vtkMatrix4x4()
        image_node.GetIJKToRASMatrix(ijk_to_ras_matrix)
        changed = False
        self._snapping_anatomy_curve_points = True
        modify_state = node.StartModify() if hasattr(node, "StartModify") else None
        try:
            for point_index in range(node.GetNumberOfControlPoints()):
                if not self._markup_control_point_is_defined(node, point_index):
                    continue
                current_point = self._markup_control_point_position(node, point_index)
                snapped_point = self._edge_snapped_ras_point(
                    current_point, image_array, ras_to_ijk_matrix, ijk_to_ras_matrix
                )
                if snapped_point is None:
                    continue
                if np.linalg.norm(snapped_point - current_point) <= EPSILON:
                    continue
                self._set_markup_control_point_position(node, point_index, snapped_point)
                changed = True
        finally:
            if modify_state is not None and hasattr(node, "EndModify"):
                node.EndModify(modify_state)
            self._snapping_anatomy_curve_points = False
        return changed

    def _is_anatomy_edge_contour_role(self, role: Any) -> bool:
        """Return whether one role is a side-specific anatomy edge-contour role."""
        return any(
            (
                role == self.side_role(base_role, side_key)
                for side_key in SIDE_KEYS
                for base_role in ANATOMY_EDGE_CONTOUR_ROLES
            )
        )

    def _edge_snap_image_array(self, image_node: Any) -> Any:
        """Return a scalar image array in Slicer's k-j-i order for edge snapping."""
        try:
            image_array = np.asarray(self.volume_array(image_node))
        except Exception:
            return None
        if image_array.size == 0:
            return None
        if image_array.ndim == 4:
            image_array = image_array[..., 0]
        if image_array.ndim == 2:
            image_array = image_array[np.newaxis, :, :]
        if image_array.ndim != 3:
            return None
        return image_array

    def _markup_control_point_is_defined(self, node: Any, point_index: int) -> bool:
        """Return whether one markup control point has a defined image position."""
        if not hasattr(node, "GetNthControlPointPositionStatus"):
            return True
        status = node.GetNthControlPointPositionStatus(point_index)
        return status == node.PositionDefined

    def _markup_control_point_position(self, node: Any, point_index: int) -> Any:
        """Return one markup control point as a NumPy RAS vector."""
        point = [0.0, 0.0, 0.0]
        if hasattr(node, "GetNthControlPointPositionWorld"):
            node.GetNthControlPointPositionWorld(point_index, point)
        else:
            node.GetNthControlPointPosition(point_index, point)
        return np.asarray(point, dtype=float)

    def _set_markup_control_point_position(self, node: Any, point_index: int, point: Any) -> None:
        """Set one markup control point in RAS coordinates."""
        if hasattr(node, "SetNthControlPointPositionWorld"):
            node.SetNthControlPointPositionWorld(point_index, float(point[0]), float(point[1]), float(point[2]))
        else:
            node.SetNthControlPointPosition(point_index, float(point[0]), float(point[1]), float(point[2]))

    def _matrix_multiply_point(self, matrix: Any, point: Any) -> Any:
        """Multiply a homogeneous 3D point by a VTK matrix and return xyz coordinates."""
        output_point = [0.0, 0.0, 0.0, 0.0]
        matrix.MultiplyPoint([float(point[0]), float(point[1]), float(point[2]), 1.0], output_point)
        weight = output_point[3] if abs(output_point[3]) > EPSILON else 1.0
        return np.asarray(output_point[:3], dtype=float) / weight

    def _edge_snapped_ras_point(
        self, ras_point: Any, image_array: Any, ras_to_ijk_matrix: Any, ijk_to_ras_matrix: Any
    ) -> Any:
        """Return the best nearby edge point in RAS coordinates for one clicked point."""
        ijk_point = self._matrix_multiply_point(ras_to_ijk_matrix, ras_point)
        candidate = self._edge_snap_candidate_ijk(image_array, ijk_point)
        if candidate is None:
            return None
        return self._matrix_multiply_point(ijk_to_ras_matrix, candidate)

    def _edge_snap_candidate_ijk(self, image_array: Any, ijk_point: Any) -> Any:
        """Find the maximum local edge-posterior point around one continuous IJK coordinate."""
        depth, height, width = image_array.shape
        k_index = int(round(float(ijk_point[2])))
        if not 0 <= k_index < depth:
            return None
        radius = int(ANATOMY_EDGE_CONTOUR_SNAP_RADIUS_PX)
        center_i = int(round(float(ijk_point[0])))
        center_j = int(round(float(ijk_point[1])))
        i_min = max(1, center_i - radius)
        i_max = min(width - 2, center_i + radius)
        j_min = max(1, center_j - radius)
        j_max = min(height - 2, center_j + radius)
        if i_min > i_max or j_min > j_max:
            return None
        gradients = []
        candidates = []
        image_slice = image_array[k_index]
        for j_index in range(j_min, j_max + 1):
            for i_index in range(i_min, i_max + 1):
                gradient = self._edge_gradient_magnitude(image_slice, i_index, j_index)
                gradients.append(gradient)
                candidates.append((i_index, j_index, gradient))
        if not gradients:
            return None
        gradient_values = np.asarray(gradients, dtype=float)
        gradient_median = float(np.median(gradient_values))
        gradient_mad = float(np.median(np.abs(gradient_values - gradient_median)))
        gradient_scale = max(1.4826 * gradient_mad, EPSILON)
        minimum_edge = gradient_median + ANATOMY_EDGE_CONTOUR_MIN_EDGE_ZSCORE * gradient_scale
        sigma = max(float(ANATOMY_EDGE_CONTOUR_SNAP_SIGMA_PX), EPSILON)
        best_score = None
        best_candidate = None
        best_gradient = None
        for i_index, j_index, gradient in candidates:
            distance_squared = (float(i_index) - ijk_point[0]) ** 2 + (float(j_index) - ijk_point[1]) ** 2
            edge_zscore = (float(gradient) - gradient_median) / gradient_scale
            score = edge_zscore - distance_squared / (2.0 * sigma * sigma)
            if best_score is None or score > best_score:
                best_score = score
                best_candidate = (i_index, j_index)
                best_gradient = gradient
        if best_candidate is None or best_gradient is None or best_gradient < minimum_edge:
            return None
        return np.asarray([float(best_candidate[0]), float(best_candidate[1]), float(ijk_point[2])], dtype=float)

    def _edge_gradient_magnitude(self, image_slice: Any, i_index: int, j_index: int) -> float:
        """Return centered finite-difference gradient magnitude for one 2D pixel."""
        gx = float(image_slice[j_index, i_index + 1]) - float(image_slice[j_index, i_index - 1])
        gy = float(image_slice[j_index + 1, i_index]) - float(image_slice[j_index - 1, i_index])
        return float(np.hypot(gx, gy))
